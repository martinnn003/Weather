export const LANGS = Object.keys(I18N);

// First a shared link, then the stored choice, then the browser's language.
export function pickLang(fromUrl, stored, browser = "") {
  for (const candidate of [fromUrl, stored]) {
    if (candidate && I18N[candidate]) return candidate;
  }
  return browser.toLowerCase().startsWith("bg") ? "bg" : "en";
}
